package com.example.demo;

/**
 * Тип извлечённого контакта.
 */
public enum ContactType {

    /** Номер телефона, найденный в тексте страницы или в ссылке tel. */
    PHONE,

    /** Email, найденный в тексте страницы или в ссылке mailto. */
    EMAIL,

    /** Почтовый адрес организации, найденный в тексте страницы. */
    ADDRESS
}
